CREATE TABLE pago (
    id                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta            NUMBER(19) NOT NULL,
    monto_pago          NUMBER(12, 2) NOT NULL CHECK (monto_pago > 0),
    metodo_pago         VARCHAR2(60) NOT NULL,
    estado_pago         VARCHAR2(30) NOT NULL,
    codigo_transaccion  VARCHAR2(60),
    codigo_autorizacion VARCHAR2(60),
    tarjeta_terminacion VARCHAR2(10),
    email_comprobante   VARCHAR2(150),
    nombre_titular      VARCHAR2(150),
    fecha_pago          TIMESTAMP NOT NULL,
    fecha_pago_chile    VARCHAR2(50),
    zona_horaria        VARCHAR2(50) DEFAULT 'America/Santiago' NOT NULL
);

CREATE INDEX idx_pago_id_venta ON pago (id_venta);
CREATE UNIQUE INDEX idx_pago_codigo_trx ON pago (codigo_transaccion);
