CREATE TABLE inventario (
    id                        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_producto           VARCHAR2(40) NOT NULL,
    nombre_producto           VARCHAR2(200) NOT NULL,
    stock_actual              NUMBER(10) NOT NULL CHECK (stock_actual >= 0),
    stock_minimo              NUMBER(10) NOT NULL CHECK (stock_minimo >= 0),
    ubicacion_bodega          VARCHAR2(150),
    estado_stock              VARCHAR2(30) NOT NULL,
    fecha_actualizacion       TIMESTAMP NOT NULL,
    fecha_actualizacion_chile VARCHAR2(50),
    zona_horaria              VARCHAR2(50) DEFAULT 'America/Santiago' NOT NULL,
    version                   NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT uk_inventario_codigo UNIQUE (codigo_producto)
);

CREATE TABLE movimiento_inventario (
    id                     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inventario          NUMBER(19) NOT NULL,
    codigo_producto        VARCHAR2(40) NOT NULL,
    tipo_movimiento        VARCHAR2(40) NOT NULL,
    cantidad               NUMBER(10) NOT NULL CHECK (cantidad >= 0),
    stock_anterior         NUMBER(10) NOT NULL,
    stock_nuevo            NUMBER(10) NOT NULL CHECK (stock_nuevo >= 0),
    observacion            VARCHAR2(300),
    estado_movimiento      VARCHAR2(30) NOT NULL,
    fecha_movimiento       TIMESTAMP NOT NULL,
    fecha_movimiento_chile VARCHAR2(50),
    zona_horaria           VARCHAR2(50) DEFAULT 'America/Santiago' NOT NULL,
    CONSTRAINT fk_mov_inventario FOREIGN KEY (id_inventario) REFERENCES inventario (id)
);

CREATE INDEX idx_mov_inv_id_inventario ON movimiento_inventario (id_inventario);
CREATE INDEX idx_mov_inv_codigo_fecha ON movimiento_inventario (codigo_producto, fecha_movimiento DESC);
