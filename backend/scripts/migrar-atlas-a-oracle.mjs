#!/usr/bin/env node
/**
 * ============================================================================
 * El Volcán — Generador de Migración MongoDB Atlas -> Oracle SQL (Idempotente)
 * ============================================================================
 * Lee los documentos existentes de `usuario`, `inventario`, `movimiento_inventario`
 * y `pago` desde MongoDB Atlas (usando MONGO_URI en backend/.env) o desde un
 * archivo JSON local (`--from-json=<ruta>`), y genera scripts SQL idempotentes
 * (`MERGE INTO`) listos para ejecutar en OCI Database Actions / SQL*Plus en
 * cada esquema dedicado (`ELVOLCAN_USUARIO`, `ELVOLCAN_INVENTARIO`, `ELVOLCAN_PAGO`).
 *
 * Uso:
 *   # Desde MongoDB Atlas (requiere paquete `mongodb` disponible en NODE_PATH o instalado):
 *   node backend/scripts/migrar-atlas-a-oracle.mjs
 *
 *   # Desde un respaldo JSON local con colecciones { usuario, inventario, movimiento_inventario, pago }:
 *   node backend/scripts/migrar-atlas-a-oracle.mjs --from-json=backend/scripts/backup-atlas.json
 * ============================================================================
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BACKEND_DIR = path.resolve(__dirname, '..');
const ENV_PATH = path.join(BACKEND_DIR, '.env');
const OUT_DIR = path.join(__dirname, 'out');

function cargarEnv(envFile) {
  const vars = {};
  if (!fs.existsSync(envFile)) return vars;
  for (const linea of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const limpia = linea.trim();
    if (!limpia || limpia.startsWith('#')) continue;
    const eq = limpia.indexOf('=');
    if (eq === -1) continue;
    vars[limpia.slice(0, eq).trim()] = limpia.slice(eq + 1).trim();
  }
  return vars;
}

function sqlStr(val) {
  if (val === null || val === undefined) return 'NULL';
  const s = String(val).replace(/'/g, "''");
  return `'${s}'`;
}

function sqlNum(val) {
  if (val === null || val === undefined || Number.isNaN(Number(val))) return 'NULL';
  return String(Number(val));
}

function sqlBool(val, def = 1) {
  if (val === null || val === undefined) return String(def);
  return val ? '1' : '0';
}

function sqlTs(val) {
  if (!val) return 'SYSTIMESTAMP';
  const d = val instanceof Date ? val : new Date(val);
  if (Number.isNaN(d.getTime())) return 'SYSTIMESTAMP';
  const pad = (n) => String(n).padStart(2, '0');
  // Formateo ISO UTC o fecha simple compatible con TO_TIMESTAMP
  const iso = `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())}`;
  return `TO_TIMESTAMP('${iso}', 'YYYY-MM-DD HH24:MI:SS')`;
}

function extraerLatLng(ubicacion) {
  const coords = ubicacion?.coordinates;
  if (Array.isArray(coords) && coords.length >= 2) {
    return { lng: Number(coords[0]), lat: Number(coords[1]) };
  }
  return { lat: null, lng: null };
}

function generarSqlUsuario(docs) {
  const lines = [
    '-- Ejecutar conectado como ELVOLCAN_USUARIO',
    '-- Migración idempotente de usuarios desde MongoDB Atlas a Oracle SQL',
    ''
  ];
  for (const u of docs) {
    const id = u._id ?? u.id;
    const { lat, lng } = extraerLatLng(u.ubicacion_actual);
    const rut = u.rut && String(u.rut).trim() ? String(u.rut).trim() : null;
    lines.push(
      `MERGE INTO usuario dst USING (SELECT ${sqlNum(id)} AS id FROM dual) src ON (dst.id = src.id)`,
      `WHEN NOT MATCHED THEN INSERT (id, nombre, apellido, password, email, rut, telefono, direccion, comuna, rol, tipo_cliente, id_zona, patente_camion, lat_actual, lng_actual, activo)`,
      `VALUES (${sqlNum(id)}, ${sqlStr(u.nombre)}, ${sqlStr(u.apellido)}, ${sqlStr(u.password)}, ${sqlStr((u.email || '').toLowerCase())}, ${sqlStr(rut)}, ${sqlStr(u.telefono)}, ${sqlStr(u.direccion)}, ${sqlStr(u.comuna)}, ${sqlStr(u.rol || 'CLIENTE')}, ${sqlStr(u.tipo_cliente)}, ${sqlNum(u.id_zona)}, ${sqlStr(u.patente_camion)}, ${sqlNum(lat)}, ${sqlNum(lng)}, ${sqlBool(u.activo, 1)});`,
      ''
    );
  }
  lines.push(
    'ALTER TABLE usuario MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE));',
    'COMMIT;'
  );
  return lines.join('\n');
}

function generarSqlInventario(invDocs, movDocs) {
  const lines = [
    '-- Ejecutar conectado como ELVOLCAN_INVENTARIO',
    '-- Migración idempotente de inventario y movimientos desde MongoDB Atlas a Oracle SQL',
    ''
  ];
  for (const i of invDocs) {
    const id = i._id ?? i.id;
    lines.push(
      `MERGE INTO inventario dst USING (SELECT ${sqlNum(id)} AS id FROM dual) src ON (dst.id = src.id)`,
      `WHEN NOT MATCHED THEN INSERT (id, codigo_producto, nombre_producto, stock_actual, stock_minimo, ubicacion_bodega, estado_stock, fecha_actualizacion, fecha_actualizacion_chile, zona_horaria, version)`,
      `VALUES (${sqlNum(id)}, ${sqlStr(i.codigo_producto)}, ${sqlStr(i.nombre_producto)}, ${sqlNum(i.stock_actual ?? 0)}, ${sqlNum(i.stock_minimo ?? 0)}, ${sqlStr(i.ubicacion_bodega)}, ${sqlStr(i.estado_stock || 'OK')}, ${sqlTs(i.fecha_actualizacion)}, ${sqlStr(i.fecha_actualizacion_chile)}, ${sqlStr(i.zona_horaria || 'America/Santiago')}, 0);`,
      ''
    );
  }
  for (const m of movDocs) {
    const id = m._id ?? m.id;
    lines.push(
      `MERGE INTO movimiento_inventario dst USING (SELECT ${sqlNum(id)} AS id FROM dual) src ON (dst.id = src.id)`,
      `WHEN NOT MATCHED THEN INSERT (id, id_inventario, codigo_producto, tipo_movimiento, cantidad, stock_anterior, stock_nuevo, observacion, estado_movimiento, fecha_movimiento, fecha_movimiento_chile, zona_horaria)`,
      `VALUES (${sqlNum(id)}, ${sqlNum(m.id_inventario)}, ${sqlStr(m.codigo_producto)}, ${sqlStr(m.tipo_movimiento)}, ${sqlNum(m.cantidad ?? 0)}, ${sqlNum(m.stock_anterior ?? 0)}, ${sqlNum(m.stock_nuevo ?? 0)}, ${sqlStr(m.observacion)}, ${sqlStr(m.estado_movimiento || 'COMPLETADO')}, ${sqlTs(m.fecha_movimiento)}, ${sqlStr(m.fecha_movimiento_chile)}, ${sqlStr(m.zona_horaria || 'America/Santiago')});`,
      ''
    );
  }
  lines.push(
    'ALTER TABLE inventario MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE));',
    'ALTER TABLE movimiento_inventario MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE));',
    'COMMIT;'
  );
  return lines.join('\n');
}

function generarSqlPago(docs) {
  const lines = [
    '-- Ejecutar conectado como ELVOLCAN_PAGO',
    '-- Migración idempotente de pagos desde MongoDB Atlas a Oracle SQL',
    ''
  ];
  for (const p of docs) {
    const id = p._id ?? p.id;
    lines.push(
      `MERGE INTO pago dst USING (SELECT ${sqlNum(id)} AS id FROM dual) src ON (dst.id = src.id)`,
      `WHEN NOT MATCHED THEN INSERT (id, id_venta, monto_pago, metodo_pago, estado_pago, codigo_transaccion, codigo_autorizacion, tarjeta_terminacion, email_comprobante, nombre_titular, fecha_pago, fecha_pago_chile, zona_horaria)`,
      `VALUES (${sqlNum(id)}, ${sqlNum(p.id_venta)}, ${sqlNum(p.monto_pago)}, ${sqlStr(p.metodo_pago)}, ${sqlStr(p.estado_pago || 'PAGADO')}, ${sqlStr(p.codigo_transaccion)}, ${sqlStr(p.codigo_autorizacion)}, ${sqlStr(p.tarjeta_terminacion)}, ${sqlStr(p.email_comprobante)}, ${sqlStr(p.nombre_titular)}, ${sqlTs(p.fecha_pago)}, ${sqlStr(p.fecha_pago_chile)}, ${sqlStr(p.zona_horaria || 'America/Santiago')});`,
      ''
    );
  }
  lines.push(
    'ALTER TABLE pago MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE));',
    'COMMIT;'
  );
  return lines.join('\n');
}

async function leerDatosOrigen() {
  const fromJsonArg = process.argv.find((a) => a.startsWith('--from-json='));
  if (fromJsonArg) {
    const ruta = path.resolve(process.cwd(), fromJsonArg.split('=')[1]);
    return JSON.parse(fs.readFileSync(ruta, 'utf8'));
  }

  const env = cargarEnv(ENV_PATH);
  const mongoUri = process.env.MONGO_URI || env.MONGO_URI;
  const mongoDb = process.env.MONGO_DB || env.MONGO_DB || 'el_volcan_db';

  if (!mongoUri) {
    throw new Error('Define MONGO_URI en backend/.env o pasa --from-json=<archivo.json>');
  }

  let MongoClient;
  try {
    ({ MongoClient } = await import('mongodb'));
  } catch {
    throw new Error(
      'Instala el driver temporalmente con `npm install --no-save mongodb` para exportar directo desde Atlas, o usa `--from-json=<archivo.json>`.'
    );
  }

  const client = new MongoClient(mongoUri);
  await client.connect();
  try {
    const db = client.db(mongoDb);
    const [usuario, inventario, movimiento_inventario, pago] = await Promise.all([
      db.collection('usuario').find({}).sort({ _id: 1 }).toArray(),
      db.collection('inventario').find({}).sort({ _id: 1 }).toArray(),
      db.collection('movimiento_inventario').find({}).sort({ _id: 1 }).toArray(),
      db.collection('pago').find({}).sort({ _id: 1 }).toArray()
    ]);
    return { usuario, inventario, movimiento_inventario, pago };
  } finally {
    await client.close();
  }
}

async function main() {
  const datos = await leerDatosOrigen();
  fs.mkdirSync(OUT_DIR, { recursive: true });

  fs.writeFileSync(path.join(OUT_DIR, 'oracle-import-usuario.sql'), generarSqlUsuario(datos.usuario || []), 'utf8');
  fs.writeFileSync(
    path.join(OUT_DIR, 'oracle-import-inventario.sql'),
    generarSqlInventario(datos.inventario || [], datos.movimiento_inventario || []),
    'utf8'
  );
  fs.writeFileSync(path.join(OUT_DIR, 'oracle-import-pago.sql'), generarSqlPago(datos.pago || []), 'utf8');

  console.log(`Scripts generados correctamente en ${OUT_DIR}:`);
  console.log(`  - oracle-import-usuario.sql (${(datos.usuario || []).length} usuarios)`);
  console.log(
    `  - oracle-import-inventario.sql (${(datos.inventario || []).length} productos, ${(datos.movimiento_inventario || []).length} movimientos)`
  );
  console.log(`  - oracle-import-pago.sql (${(datos.pago || []).length} pagos)`);
}

main().catch((err) => {
  console.error('[ERROR migrar-atlas-a-oracle]', err.message);
  process.exit(1);
});
