CREATE TABLE usuario (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR2(100) NOT NULL,
    apellido        VARCHAR2(100) NOT NULL,
    password        VARCHAR2(255) NOT NULL,
    email           VARCHAR2(150) NOT NULL,
    rut             VARCHAR2(20),
    telefono        VARCHAR2(40),
    direccion       VARCHAR2(250),
    comuna          VARCHAR2(100),
    rol             VARCHAR2(30) NOT NULL,
    tipo_cliente    VARCHAR2(40),
    id_zona         NUMBER(10),
    patente_camion  VARCHAR2(30),
    lat_actual      NUMBER(10, 6),
    lng_actual      NUMBER(10, 6),
    activo          NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0, 1)),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT uk_usuario_rut UNIQUE (rut)
);

CREATE INDEX idx_usuario_rol ON usuario (rol);
